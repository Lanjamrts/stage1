CREATE TABLE PROFIL (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_PROFIL PRIMARY KEY,
  CODE VARCHAR2(20 CHAR) NOT NULL,
  LABEL VARCHAR2(100 CHAR) NOT NULL,
  CREATED_AT TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT UQ_PROFIL_CODE UNIQUE (CODE)
);

CREATE TABLE REGION (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_REGION PRIMARY KEY,
  NAME_REGION VARCHAR2(100 CHAR) NOT NULL,
  CREATED_AT TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT UQ_REGION_NAME_REGION UNIQUE (NAME_REGION)
);

CREATE TABLE STRUCTURE (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_STRUCTURE PRIMARY KEY,
  CODE VARCHAR2(30 CHAR) NOT NULL,
  LABEL VARCHAR2(200 CHAR) NOT NULL,
  TYPE_STRUCTURE VARCHAR2(12 CHAR) NOT NULL CONSTRAINT CK_STRUCTURE_TYPE_STRUCTURE CHECK (TYPE_STRUCTURE IN ('SRB','SRSP','SRPE','CIRBF','DRBF','SSEBF','DGBF','CELLULE_INFO')),
  REGION_ID NUMBER,
  ACTIVE NUMBER(1) DEFAULT 1 NOT NULL CONSTRAINT CK_STRUCTURE_ACTIVE CHECK (ACTIVE IN (0,1)),
  CREATED_AT TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT UQ_STRUCTURE_CODE UNIQUE (CODE),
  CONSTRAINT FK_STRUCTURE_REGION_ID FOREIGN KEY (REGION_ID) REFERENCES REGION (ID)
);

CREATE INDEX IX_STRUCTURE_REGION_ID ON STRUCTURE (REGION_ID);

CREATE TABLE UTILISATEUR (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_UTILISATEUR PRIMARY KEY,
  IM VARCHAR2(20 CHAR) NOT NULL,
  NOM VARCHAR2(100 CHAR) NOT NULL,
  PRENOM VARCHAR2(100 CHAR) NOT NULL,
  DIRECTION VARCHAR2(200 CHAR) NOT NULL,
  SERVICE VARCHAR2(200 CHAR) NOT NULL,
  PASSWORD_HASH VARCHAR2(255 CHAR) NOT NULL,
  ROLE_CODE VARCHAR2(11 CHAR) NOT NULL CONSTRAINT CK_UTILISATEUR_ROLE_CODE CHECK (ROLE_CODE IN ('client','admin2','admin1','developpeur','consultant')),
  STRUCTURE_ID NUMBER NOT NULL,
  STATUT VARCHAR2(9 CHAR) DEFAULT 'actif' NOT NULL CONSTRAINT CK_UTILISATEUR_STATUT CHECK (STATUT IN ('actif','desactive')),
  MUST_CHANGE_PASSWORD NUMBER(1) DEFAULT 0 NOT NULL CONSTRAINT CK_UTILISATEUR_MUST_CHANGE_PASSWORD CHECK (MUST_CHANGE_PASSWORD IN (0,1)),
  FAILED_ATTEMPTS NUMBER(5) DEFAULT 0 NOT NULL,
  LOCKED_UNTIL TIMESTAMP(3) WITH TIME ZONE,
  CREATED_AT TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT UQ_UTILISATEUR_IM UNIQUE (IM),
  CONSTRAINT FK_UTILISATEUR_STRUCTURE_ID FOREIGN KEY (STRUCTURE_ID) REFERENCES STRUCTURE (ID)
);

CREATE INDEX IX_UTILISATEUR_STRUCTURE_ID ON UTILISATEUR (STRUCTURE_ID);

CREATE TABLE PERIODE (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_PERIODE PRIMARY KEY,
  LABEL VARCHAR2(100 CHAR) NOT NULL,
  DATE_DEBUT TIMESTAMP(3) WITH TIME ZONE NOT NULL,
  DATE_FIN TIMESTAMP(3) WITH TIME ZONE NOT NULL,
  DATE_LIMITE TIMESTAMP(3) WITH TIME ZONE NOT NULL,
  PERIODICITE VARCHAR2(10 CHAR) NOT NULL CONSTRAINT CK_PERIODE_PERIODICITE CHECK (PERIODICITE IN ('monthly','quarterly')),
  CREATED_AT TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE UNIQUE INDEX UQ_PERIODE_PERIODICITE_DATE_DEBUT ON PERIODE (PERIODICITE, DATE_DEBUT);

CREATE TABLE MODULE_SIGBD (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_MODULE_SIGBD PRIMARY KEY,
  CODE VARCHAR2(50 CHAR) NOT NULL,
  LABEL VARCHAR2(200 CHAR) NOT NULL,
  PERIODICITE VARCHAR2(10 CHAR) NOT NULL CONSTRAINT CK_MODULE_SIGBD_PERIODICITE CHECK (PERIODICITE IN ('monthly','quarterly')),
  GENRE VARCHAR2(8 CHAR) NOT NULL CONSTRAINT CK_MODULE_SIGBD_GENRE CHECK (GENRE IN ('periodic','event')),
  VERSION_MODULE NUMBER(5) DEFAULT 1 NOT NULL,
  ACTIVE NUMBER(1) DEFAULT 1 NOT NULL CONSTRAINT CK_MODULE_SIGBD_ACTIVE CHECK (ACTIVE IN (0,1)),
  FIELDS_JSON JSON NOT NULL,
  CREATED_AT TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT UQ_MODULE_SIGBD_CODE UNIQUE (CODE)
);

CREATE TABLE MODULE_PERIODICITE (
  MODULE_ID NUMBER NOT NULL,
  PERIODICITE VARCHAR2(10 CHAR) NOT NULL CONSTRAINT CK_MODULE_PERIODICITE_PERIODICITE CHECK (PERIODICITE IN ('monthly','quarterly')),
  CREATED_AT TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_MODULE_PERIODICITE PRIMARY KEY (MODULE_ID, PERIODICITE),
  CONSTRAINT FK_MODULE_PERIODICITE_MODULE_ID FOREIGN KEY (MODULE_ID) REFERENCES MODULE_SIGBD (ID) ON DELETE CASCADE
);

CREATE TABLE MODULE_TYPE_STRUCTURE (
  MODULE_ID NUMBER NOT NULL,
  TYPE_STRUCTURE VARCHAR2(12 CHAR) NOT NULL CONSTRAINT CK_MODULE_TYPE_STRUCTURE_TYPE_STRUCTURE CHECK (TYPE_STRUCTURE IN ('SRB','SRSP','SRPE','CIRBF','DRBF','SSEBF','DGBF','CELLULE_INFO')),
  CREATED_AT TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT PK_MODULE_TYPE_STRUCTURE PRIMARY KEY (MODULE_ID, TYPE_STRUCTURE),
  CONSTRAINT FK_MODULE_TYPE_STRUCTURE_MODULE_ID FOREIGN KEY (MODULE_ID) REFERENCES MODULE_SIGBD (ID) ON DELETE CASCADE
);

CREATE TABLE SAISIE (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_SAISIE PRIMARY KEY,
  STRUCTURE_ID NUMBER NOT NULL,
  MODULE_ID NUMBER NOT NULL,
  VERSION_MODULE NUMBER(5) NOT NULL,
  PERIODE_ID NUMBER,
  DATE_EVENEMENT TIMESTAMP(3) WITH TIME ZONE,
  AUTEUR_ID NUMBER NOT NULL,
  STATUT VARCHAR2(9 CHAR) DEFAULT 'brouillon' NOT NULL CONSTRAINT CK_SAISIE_STATUT CHECK (STATUT IN ('brouillon','soumise','rejetee','validee','exportee','archivee')),
  VALEURS_JSON JSON NOT NULL,
  DATE_CREATION TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  DATE_SOUMISSION TIMESTAMP(3) WITH TIME ZONE,
  DATE_EXPORT TIMESTAMP(3) WITH TIME ZONE,
  CREATED_AT TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT FK_SAISIE_STRUCTURE_ID FOREIGN KEY (STRUCTURE_ID) REFERENCES STRUCTURE (ID),
  CONSTRAINT FK_SAISIE_MODULE_ID FOREIGN KEY (MODULE_ID) REFERENCES MODULE_SIGBD (ID),
  CONSTRAINT FK_SAISIE_PERIODE_ID FOREIGN KEY (PERIODE_ID) REFERENCES PERIODE (ID),
  CONSTRAINT FK_SAISIE_AUTEUR_ID FOREIGN KEY (AUTEUR_ID) REFERENCES UTILISATEUR (ID)
);

CREATE UNIQUE INDEX UQ_SAISIE_PERIODE ON SAISIE (CASE WHEN PERIODE_ID IS NOT NULL THEN STRUCTURE_ID END, CASE WHEN PERIODE_ID IS NOT NULL THEN MODULE_ID END, PERIODE_ID);

CREATE INDEX IX_SAISIE_STRUCTURE_ID ON SAISIE (STRUCTURE_ID);

CREATE INDEX IX_SAISIE_MODULE_ID ON SAISIE (MODULE_ID);

CREATE INDEX IX_SAISIE_PERIODE_ID ON SAISIE (PERIODE_ID);

CREATE INDEX IX_SAISIE_AUTEUR_ID ON SAISIE (AUTEUR_ID);

CREATE INDEX IX_SAISIE_STATUT ON SAISIE (STATUT);

CREATE TABLE SAISIE_VALIDATION (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_SAISIE_VALIDATION PRIMARY KEY,
  SAISIE_ID NUMBER NOT NULL,
  DECISION VARCHAR2(8 CHAR) NOT NULL CONSTRAINT CK_SAISIE_VALIDATION_DECISION CHECK (DECISION IN ('soumise','validee','rejetee','exportee')),
  MOTIF VARCHAR2(500 CHAR),
  ACTEUR_ID NUMBER,
  ACTEUR_LABEL VARCHAR2(200 CHAR),
  DATE_DECISION TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CREATED_AT TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT FK_SAISIE_VALIDATION_SAISIE_ID FOREIGN KEY (SAISIE_ID) REFERENCES SAISIE (ID) ON DELETE CASCADE,
  CONSTRAINT FK_SAISIE_VALIDATION_ACTEUR_ID FOREIGN KEY (ACTEUR_ID) REFERENCES UTILISATEUR (ID)
);

CREATE INDEX IX_SAISIE_VALIDATION_SAISIE_DATE ON SAISIE_VALIDATION (SAISIE_ID, DATE_DECISION);

CREATE INDEX IX_SAISIE_VALIDATION_ACTEUR_ID ON SAISIE_VALIDATION (ACTEUR_ID);

CREATE TABLE REFERENTIEL (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_REFERENTIEL PRIMARY KEY,
  TYPE_REF VARCHAR2(11 CHAR) NOT NULL CONSTRAINT CK_REFERENTIEL_TYPE_REF CHECK (TYPE_REF IN ('directions','services','grades','epn','std','ministeres')),
  VALEUR VARCHAR2(500 CHAR) NOT NULL,
  MINISTERE VARCHAR2(200 CHAR),
  REGIME VARCHAR2(100 CHAR),
  ACRONYME VARCHAR2(50 CHAR),
  CREATED_AT TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT UQ_REFERENTIEL_TYPE_VALEUR UNIQUE (TYPE_REF, VALEUR)
);

CREATE TABLE REMARQUE (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_REMARQUE PRIMARY KEY,
  AUTEUR_ID NUMBER NOT NULL,
  CONTEXTE VARCHAR2(500 CHAR) NOT NULL,
  TEXTE VARCHAR2(2000 CHAR) NOT NULL,
  ETAT VARCHAR2(8 CHAR) DEFAULT 'nouvelle' NOT NULL CONSTRAINT CK_REMARQUE_ETAT CHECK (ETAT IN ('nouvelle','en_cours','traitee')),
  CREATED_AT TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT FK_REMARQUE_AUTEUR_ID FOREIGN KEY (AUTEUR_ID) REFERENCES UTILISATEUR (ID)
);

CREATE INDEX IX_REMARQUE_AUTEUR_ID ON REMARQUE (AUTEUR_ID);

CREATE TABLE JOURNAL_AUDIT (
  ID NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT PK_JOURNAL_AUDIT PRIMARY KEY,
  USER_REF VARCHAR2(64 CHAR) NOT NULL,
  ACTION VARCHAR2(64 CHAR) NOT NULL,
  OBJET VARCHAR2(200 CHAR) NOT NULL,
  IP VARCHAR2(64 CHAR) NOT NULL,
  CREATED_AT TIMESTAMP(3) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL
);

CREATE INDEX IX_JOURNAL_AUDIT_DATE ON JOURNAL_AUDIT (CREATED_AT DESC);

CREATE INDEX IX_JOURNAL_AUDIT_USER ON JOURNAL_AUDIT (USER_REF, CREATED_AT DESC);
