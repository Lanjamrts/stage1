// Libellé d'affichage du service : connect string seule, jamais l'utilisateur
// ni le mot de passe (même sélection que nomOracle() de connexion.js).
export function nomServiceOracle(config) {
  const service =
    config.NODE_ENV === 'test' && config.ORACLE_TEST_CONNECT_STRING
      ? config.ORACLE_TEST_CONNECT_STRING
      : config.ORACLE_CONNECT_STRING;
  return service || '127.0.0.1:1521/XEPDB1';
}

// Fragment de nom de fichier déduit du service (« XEPDB1 »), sans ponctuation.
export function slugService(service) {
  const morceau = service.includes('/') ? service.slice(service.lastIndexOf('/') + 1) : service;
  const propre = morceau.replace(/[^A-Za-z0-9_-]+/g, '-').replace(/^-+|-+$/g, '');
  return propre || 'oracle';
}

// Même horodatage que la sauvegarde MongoDB (backup.js), millisecondes prises
// sur la même date que le reste du nom pour rester cohérent.
export function horodatageFichier(date = new Date()) {
  return date.toISOString().replace(/[-:]/g, '').split('.')[0] + '-' + date.getMilliseconds() + 'Z';
}

export function nomFichierOracle(service, date = new Date()) {
  return `sigbd-oracle-${slugService(service)}-${horodatageFichier(date)}${EXTENSION}`;
}

export function analyserArgs(argv) {
  const options = { output: null };
  const erreurs = [];
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--output') {
      if (i + 1 >= argv.length) {
        erreurs.push('Option --output : fichier attendu.');
        break;
      }
      options.output = argv[i + 1];
      i++;
    } else {
      erreurs.push(`Option inconnue : ${argv[i]}`);
    }
  }
  return { ...options, erreurs };
}

// Une valeur lue est normalisée pour le fichier : dates en ISO 8601, colonnes
// JSON conservées telles quelles (objet ou chaîne), le reste inchangé.
export function normaliserValeur(valeur, type) {
  if (valeur === undefined || valeur === null) return null;
  if (type === 'date') {
    return valeur instanceof Date ? valeur.toISOString() : String(valeur);
  }
  if (type === 'json') {
    if (Buffer.isBuffer(valeur)) {
      try {
        return JSON.parse(valeur.toString('utf8'));
      } catch {
        return valeur.toString('utf8');
      }
    }
    if (typeof valeur === 'string') {
      try {
        return JSON.parse(valeur);
      } catch {
        return valeur;
      }
    }
    return valeur;
  }
  return valeur;
}

// Ligne → objet du fichier, colonne par colonne selon la définition.
export function normaliserLigne(ligne, definition) {
  const sortie = {};
  for (const colonne of definition.colonnes) {
    sortie[colonne.nom] = normaliserValeur(ligne[colonne.nom], colonne.type);
  }
  return sortie;
}

export function definitionDe(nomTable) {
  return TABLES.find((definition) => definition.nom === nomTable) || null;
}

// En-tête + tables, dans l'ordre canonique des clés : la somme de contrôle se
// recalcule donc à l'identique depuis un fichier relu, quel que soit l'ordre
// des clés dans le fichier.
export function construireEnveloppe(fichier) {
  return {
    format: fichier.format,
    version: fichier.version,
    date: fichier.date,
    service: fichier.service,
    counts: fichier.counts,
    tables: fichier.tables,
  };
}

// Fichier neuf à partir des sections lues (une par table, ordre de TABLES).
export function construireFichier({ date, service, sections }) {
  const counts = {};
  const tables = [];
  for (const definition of TABLES) {
    const section = sections.find((s) => s.name === definition.nom);
    if (!section || !Array.isArray(section.rows)) {
      throw new Error(`Section manquante pour la table ${definition.nom}.`);
    }
    counts[definition.nom] = section.rows.length;
    tables.push({ name: definition.nom, rows: section.rows });
  }
  return { format: FORMAT, version: VERSION, date, service, counts, tables };
}

export function calculerSomme(fichier) {
  return createHash('sha256').update(JSON.stringify(construireEnveloppe(fichier)), 'utf8').digest('hex');
}

export function verifierSomme(fichier) {
  const attendu = fichier.sha256;
  const obtenu = calculerSomme(fichier);
  return { ok: typeof attendu === 'string' && attendu === obtenu, attendu, obtenu };
}

// Les 13 tables présentes une fois chacune, sans doublon ni table inconnue,
// et chaque ligne limitée aux colonnes déclarées (le SQL ne sort pas de là).
export function verifierStructure(fichier) {
  const erreurs = [];
  if (!Array.isArray(fichier.tables)) {
    return ['Le champ « tables » doit être un tableau.'];
  }
  if (!fichier.counts || typeof fichier.counts !== 'object' || Array.isArray(fichier.counts)) {
    erreurs.push('Le champ « counts » doit être un objet.');
  }
  const noms = fichier.tables.map((section) => section && section.name);
  for (const definition of TABLES) {
    const occurrences = noms.filter((nom) => nom === definition.nom).length;
    if (occurrences !== 1) {
      erreurs.push(`Table ${definition.nom} : ${occurrences} section(s), attendu 1.`);
      continue;
    }
    const section = fichier.tables.find((s) => s.name === definition.nom);
    if (!Array.isArray(section.rows)) {
      erreurs.push(`Table ${definition.nom} : « rows » doit être un tableau.`);
      continue;
    }
    const attendues = new Set(definition.colonnes.map((c) => c.nom));
    section.rows.forEach((ligne, index) => {
      if (!ligne || typeof ligne !== 'object' || Array.isArray(ligne)) {
        erreurs.push(`Table ${definition.nom} ligne ${index + 1} : objet attendu.`);
        return;
      }
      for (const cle of Object.keys(ligne)) {
        if (!attendues.has(cle)) {
          erreurs.push(`Table ${definition.nom} ligne ${index + 1} : colonne inconnue ${cle}.`);
        }
      }
    });
  }
  for (const nom of noms) {
    if (!definitionDe(nom)) erreurs.push(`Table inconnue dans le fichier : ${nom}.`);
  }
  return erreurs;
}

// Comptes de l'en-tête exactement égaux au nombre de lignes de chaque table.
export function verifierComptes(fichier) {
  const erreurs = [];
  if (!fichier.counts || typeof fichier.counts !== 'object') {
    return ['Le champ « counts » est absent.'];
  }
  const nomsAttendus = TABLES.map((definition) => definition.nom);
  for (const nom of Object.keys(fichier.counts)) {
    if (!nomsAttendus.includes(nom)) erreurs.push(`Compte inattendu : ${nom}.`);
  }
  for (const definition of TABLES) {
    const section = Array.isArray(fichier.tables)
      ? fichier.tables.find((s) => s.name === definition.nom)
      : null;
    const lignes = section && Array.isArray(section.rows) ? section.rows.length : null;
    if (fichier.counts[definition.nom] !== lignes) {
      erreurs.push(
        `Compte ${definition.nom} : ${fichier.counts[definition.nom]} dans l'en-tête, ${lignes} ligne(s) dans le fichier.`
      );
    }
  }
  return erreurs;
}

// Lecture + contrôle complet d'un fichier : format, version, structure,
// somme de contrôle, comptes. Aucune connexion, aucun mot de passe.
export function lireFichierBackup(chemin) {
  let brut;
  try {
    brut = readFileSync(chemin, 'utf8');
  } catch {
    return { ok: false, fichier: null, erreurs: [`Fichier illisible : ${chemin}`] };
  }
  let fichier;
  try {
    fichier = JSON.parse(brut);
  } catch {
    return { ok: false, fichier: null, erreurs: ['Fichier JSON illisible.'] };
  }
  if (!fichier || typeof fichier !== 'object' || Array.isArray(fichier)) {
    return { ok: false, fichier: null, erreurs: ['Format de sauvegarde attendu : objet JSON.'] };
  }
  const erreurs = [];
  if (fichier.format !== FORMAT) {
    erreurs.push(`Format inconnu : ${JSON.stringify(fichier.format)} (attendu ${FORMAT}).`);
  }
  if (fichier.version !== VERSION) {
    erreurs.push(`Version inconnue : ${JSON.stringify(fichier.version)} (attendue ${VERSION}).`);
  }
  if (erreurs.length === 0) {
    erreurs.push(...verifierStructure(fichier));
  }
  if (erreurs.length === 0) {
    const { ok, attendu, obtenu } = verifierSomme(fichier);
    if (!ok) {
      erreurs.push(
        `Somme de contrôle SHA-256 incorrecte (attendu ${attendu ?? '(absente)'}, obtenu ${obtenu}).`
      );
    }
  }
  if (erreurs.length === 0) {
    erreurs.push(...verifierComptes(fichier));
  }
  return { ok: erreurs.length === 0, fichier, erreurs };
}

// Maximum de la colonne d'identité d'une section (null si aucune ligne).
export function maxIdSection(section) {
  if (!section || !Array.isArray(section.rows) || section.rows.length === 0) return null;
  let max = null;
  for (const ligne of section.rows) {
    const valeur = ligne ? ligne.ID : null;
    if (typeof valeur !== 'number' || !Number.isFinite(valeur)) continue;
    if (max === null || valeur > max) max = valeur;
  }
  return max;
}

