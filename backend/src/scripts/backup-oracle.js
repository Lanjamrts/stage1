export async function main(argv = process.argv.slice(2)) {
  const { output, erreurs } = analyserArgs(argv);
  if (erreurs.length > 0) {
    for (const erreur of erreurs) console.error(erreur);
    console.error('');
    console.error('Usage : node src/scripts/backup-oracle.js [--output <fichier>]');
    return 1;
  }

  const config = loadConfig();
  const service = nomServiceOracle(config);
  const backupDir = getBackupDir();
  const chemin = output ? resolve(output) : join(backupDir, nomFichierOracle(service));

  if (existsSync(chemin)) {
    console.error(`Le fichier de destination existe déjà : ${chemin}`);
    return 1;
  }

  let sections;
  try {
    const db = await getKnex();
    sections = await lireTables(db);
  } catch (err) {
    console.error(`Échec de la lecture Oracle : ${messageErreurOracle(err)}`);
    try {
      await closeOracle();
    } catch {
      /* pool déjà fermé */
    }
    return 1;
  }
  try {
    await closeOracle();
  } catch {
    /* pool déjà fermé */
  }

  let fichier;
  let somme;
  try {
    fichier = construireFichier({ date: new Date().toISOString(), service, sections });
    somme = calculerSomme(fichier);
    writeFileSync(chemin, JSON.stringify({ ...fichier, sha256: somme }, null, 2), { mode: 0o600 });
    chmodSync(chemin, 0o600);
  } catch (err) {
    console.error(`Échec de l'écriture du fichier : ${err.message}`);
    return 1;
  }

  console.log(`Sauvegarde créée : ${chemin}`);
  console.log(`Service : ${service}`);
  console.log(`Taille : ${formatSize(statSync(chemin).size)}`);
  console.log(`Date : ${fichier.date}`);
  for (const definition of TABLES) {
    console.log(`  ${definition.nom.padEnd(21)} : ${fichier.counts[definition.nom]} ligne(s)`);
  }
  console.log(`Somme de contrôle SHA-256 : ${somme}`);
  console.log('');
  console.log(
    'Copiez cette sauvegarde en dehors du serveur. Elle contient des données sensibles (empreintes de mots de passe).'
  );
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().then(
    (code) => process.exit(code),
    (err) => {
      console.error(`Échec de la sauvegarde Oracle : ${err && err.message ? err.message : err}`);
      process.exit(1);
    }
  );
}
